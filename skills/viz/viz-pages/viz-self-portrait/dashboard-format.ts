export function esc(s: unknown): string {
  return String(s).replaceAll(
    /[&<>"']/gu,
    (c) =>
      (
        ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }) as Record<
          string,
          string
        >
      )[c]!,
  );
}
