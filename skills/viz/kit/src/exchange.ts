// The exchange runtime — `/_kit/exchange.js`.
//
// An EXCHANGE is a diagram of something being presented, passed or proven
// between parties: actors in phase bands, declared wires between them, a
// labelled packet animating along a wire, and a stepped narration. Scaffold one
// with `viz create <slug> --from exchange`; the shape of the data is EXCHANGE.md.
//
// It is deliberately NOT a UML sequence diagram. There are no lifelines: the
// vertical axis is PHASE, not time, and an actor is repeated in each band it
// takes part in. That is the trade — you give up the continuous lifeline and
// get to say how OFTEN each band happens ("once" / "per token" / "per request"),
// which a sequence diagram cannot express.
//
// It owns the EXPERIENCE: zones, lanes, boxes, wires, animated packets that ride
// in and park, per-phase result panels, the stepper, autoscroll. It knows nothing
// about any particular protocol -- that lives in a variant's content.js.
//
// ─────────────────────────────────────────────────────────────────────────────
// DO NOT EDIT THIS FILE TO CHANGE ONE VARIANT. Every exchange in every repo
// shares it, so an edit here changes all of them. Everything a variant needs to
// differ is already data in its content.js -- see EXCHANGE.md. If you genuinely
// cannot express something as data, stop and say so rather than editing this.
//
// Regression gate: `bun check-exchange.mjs <viz-dir>` must stay green on every
// exchange in the corpus after any change here.
// ─────────────────────────────────────────────────────────────────────────────

import type { BrowserState, Exchange, ExchangeStep, Geo } from "@viz/kit/exchange-shared.js";
import { $, el, orElse } from "@viz/kit/exchange-shared.js";
import { buildNodes, buildPanels, buildScenery, buildShell } from "@viz/kit/exchange-stage.js";
import { cy, drawWires, geometry } from "@viz/kit/exchange-wires.js";
import { createPackets } from "@viz/kit/exchange-packets.js";

export type {
  BrowserState,
  Exchange,
  ExchangeNode,
  ExchangeStep,
  ParallelHop,
  WireOpts,
} from "@viz/kit/exchange-shared.js";

/** Which boxes light up for a step: its own `lit`, else its endpoints and whatever a parallel packet flies into. */
function litBoxes(s: ExchangeStep, N: Exchange["nodes"]): string[] {
  return (
    s.lit ?? [
      ...(s.from && N[s.from] && s.to && N[s.to]
        ? [s.from, s.to]
        : s.from && N[s.from]
          ? [s.from]
          : []),
      // whatever a parallel packet flies into lights up too, otherwise the log
      // hop animates into a box that still looks asleep
      ...(s.also ?? []).flatMap((a) => [a.from, a.to]).filter((id) => N[id]),
    ]
  );
}

/** Where on the stage (stage px, y) a step is about, to keep it roughly centred. */
function stepAnchor(exchange: Exchange, s: ExchangeStep, G: (id: string) => Geo): number {
  const a = s.from && G(s.from),
    b = s.to && G(s.to);
  return a && b
    ? (cy(a) + cy(b)) / 2
    : a
      ? cy(a)
      : (exchange.lanes.find((l) => l.id === s.p)?.y ?? 0) + 160;
}

export function mount(exchange: Exchange): void {
  const STEPS = exchange.steps;
  const STAGE_W = orElse(exchange.stage?.w, 1780);
  const STAGE_H = orElse(exchange.stage?.h, 1630);

  if (exchange.theme) {
    const vars = Object.entries(exchange.theme)
      .map(([k, v]) => `--${k}:${v}`)
      .join(";");
    document.head.append(el("style", null, `:root{${vars}}`));
  }

  // ---- shell and scenery -------------------------------------------------
  const { stage, svg, pktLayer } = buildShell(exchange, STAGE_W, STAGE_H);
  const N = exchange.nodes;
  const G = geometry(exchange);
  buildScenery(exchange, stage, STAGE_W);
  const nodeEls = buildNodes(exchange, stage);
  buildPanels(exchange, stage);

  // ---- wires -------------------------------------------------------------
  const wirePaths = drawWires(exchange, svg, G);

  // ---- optional travelling browser --------------------------------------
  let browser: HTMLElement | null = null;
  if (exchange.browser) {
    browser = el("div", "browser");
    browser.dataset["vizId"] = "browser";
    browser.dataset["label"] = "browser";
    browser.innerHTML = `<div class="bchrome"><span class="bdot"></span><span class="bdot"></span>
      <span class="bdot"></span><span class="burl"><span class="lock">🔒</span>
      <span id="burl"></span></span></div><div class="bbody" id="bbody"></div>`;
    stage.append(browser);
  }
  function setBrowser(b: BrowserState) {
    if (!browser) return;
    const n = G(b.at);
    browser.style.left = n.x + n.w / 2 - 135 + "px";
    browser.style.top = n.y + n.h + 30 + "px";
    $("#burl").textContent = b.url;
    $("#bbody").innerHTML = b.body;
  }

  // ---- packets -----------------------------------------------------------
  const { flyPacket, clearLive } = createPackets(pktLayer, wirePaths);

  // ---- playback ----------------------------------------------------------
  let i = 0,
    playing = false,
    timer: ReturnType<typeof setInterval> | undefined,
    K = 1;
  const track = $("#track");
  STEPS.forEach((_, k) => {
    const t = el("div", "tick");
    t.addEventListener("click", () => {
      stop();
      go(k);
    });
    track.append(t);
  });

  function render() {
    const s = STEPS[i];
    if (!s) return;
    $("#stepno").innerHTML = i + 1 + "<small>of " + STEPS.length + "</small>";
    $("#ntitle").textContent = s.t;
    [...track.children].forEach((t, k) => {
      t.className = "tick" + (k < i ? " done" : k === i ? " now" : "");
    });
    exchange.lanes.forEach((L) => {
      document.querySelector("#lane" + L.id)?.classList.toggle("active", L.id === s.p);
    });

    Object.values(nodeEls).forEach((e) => e.classList.remove("lit"));
    litBoxes(s, N).forEach((id) => nodeEls[id]?.classList.add("lit"));

    if (s.browser) setBrowser(s.browser);
    if (browser) browser.style.opacity = orElse(exchange.browserPhase, 1) === s.p ? "1" : ".3";
    // a step fills panels by id -- the engine never knows what any of them mean
    for (const [id, html] of Object.entries(s.set ?? {})) {
      const t = document.querySelector("#" + id + " .body");
      if (t) t.innerHTML = html;
    }
    // Clear once, here, then fly every packet this step wants. `s.also` is a list
    // of {from,to,pkt,ret} that animate SIMULTANEOUSLY with the main one — for
    // showing that a hop and its side effect (an audit log, a mirror write) happen
    // together rather than as separate steps later on. Added 2026-08-06.
    clearLive();
    if (s.from)
      flyPacket(s.from, s.to ?? "", s.pkt ?? "", s.ret, Boolean(s.back) || Boolean(s.hand));
    for (const a of s.also ?? []) flyPacket(a.from, a.to, a.pkt ?? "", a.ret, a.green);

    // keep whatever the step is about roughly centred -- set autoscroll:false on a
    // exchange whose stage fits on screen, where the re-centring only reads as jumping
    if (exchange.autoscroll !== false) {
      const anchor = stepAnchor(exchange, s, G);
      const top = stage.getBoundingClientRect().top + scrollY;
      scrollTo({ top: Math.max(0, top + anchor * K - (innerHeight - 96) / 2), behavior: "smooth" });
    }
    history.replaceState(null, "", "#step=" + i);
  }
  function go(k: number) {
    i = Math.max(0, Math.min(STEPS.length - 1, k));
    render();
  }
  function next() {
    if (i < STEPS.length - 1) {
      go(i + 1);
      return true;
    }
    return false;
  }
  function play() {
    playing = true;
    $("#play").textContent = "❚❚ Pause";
    clearInterval(timer);
    timer = setInterval(
      () => {
        if (!next()) stop();
      },
      orElse(exchange.stepMs, 2400),
    );
  }
  function stop() {
    playing = false;
    $("#play").textContent = "▶ Play";
    clearInterval(timer);
  }

  $("#play").addEventListener("click", () => {
    if (playing) stop();
    else play();
  });
  $("#next").addEventListener("click", () => {
    stop();
    next();
  });
  $("#prev").addEventListener("click", () => {
    stop();
    go(i - 1);
  });
  // a reload is a free, always-correct reset -- no teardown code to keep in sync
  $("#restart").addEventListener("click", () => {
    location.hash = "step=0";
    location.reload();
  });
  addEventListener("keydown", (e) => {
    if (e.key === "ArrowRight") {
      stop();
      next();
    }
    if (e.key === "ArrowLeft") {
      stop();
      go(i - 1);
    }
    if (e.key === " ") {
      e.preventDefault();
      if (playing) stop();
      else play();
    }
  });

  function fit() {
    const k = (K = Math.min(1, (innerWidth - 40) / STAGE_W));
    stage.style.transform = "scale(" + k + ")";
    // scale() shrinks the stage visually but leaves its layout box full size
    stage.style.marginBottom = -STAGE_H * (1 - k) + "px";
    stage.style.marginRight = -STAGE_W * (1 - k) + "px";
  }
  addEventListener("resize", fit);
  fit();

  if (exchange.browser) setBrowser(exchange.browser);
  // oxlint-disable-next-line unicorn/prefer-number-coercion -- parseInt keeps the leading digits of a hand-edited hash (#step=3x)
  go(Number.parseInt(new URLSearchParams(location.hash.slice(1)).get("step") ?? "0", 10) || 0);
}
